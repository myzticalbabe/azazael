def slug(text: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")
    if not cleaned:
        cleaned = "unit"
    if cleaned[0].isdigit():
        cleaned = "s_" + cleaned
    return cleaned


def real_case(parts: Sequence[str]) -> Optional[str]:
    """The on-disk spelling of a path inside the vendor tree, or None.

    The atlas records `scripts/gate_bash.py`; the directory is `SCRIPTS`. Windows
    resolves that case-insensitively for a path check, so a path probe was happy
    and the dotted name was still wrong: `import adopted.kali.scripts` raised
    `ModuleNotFoundError` because Python matches package **names**, not paths.
    Eight rows blocked on case alone (measured 2026-11-03).
    """
    base = VENDOR
    resolved: List[str] = []
    for part in parts:
        # A resolved `.py` file cannot be descended into (`METAWORMS.py` treated
        # as a directory raised NotADirectoryError), so the walk stops there.
        if not base.is_dir():
            return None
        # Never trust the spelling: `(base / "scripts").exists()` is True for a
        # directory actually named `SCRIPTS`, so asking the filesystem whether
        # the path lives is not the same question as what the entry is called.
        # A module part arrives without its suffix (`gate_bash`, from
        # `scripts/gate_bash.py`), so both spellings are candidates and a package
        # directory wins over a same-named module, as Python's own import does.
        entries = [child.name for child in base.iterdir()]
        wanted = [part, part + ".py"]
        chosen = next((name for name in wanted if name in entries), None)
        if chosen is None:
            lowered = {name.lower() for name in wanted}
            matches = sorted(name for name in entries if name.lower() in lowered)
            if not matches:
                return None
            chosen = matches[0]
        resolved.append(chosen)
        base = base / chosen
    return "/".join(resolved)


def module_path(parts: Sequence[str]) -> Optional[str]:
    """On-disk module path for `parts`, without the source suffix.

    `real_case` answers with what the file is called (`gate_bash.py`); a dotted
    module name must not carry that suffix, or every emitted import reads
    `adopted.kali.SCRIPTS.gate_bash.py`.
    """
    real = real_case(parts)
    if real is None:
        return None
    return real[:-3] if real.endswith(".py") else real


def dotted(module: str) -> str:
    """The import name for a Kali module reference (`AOA/core/event_bus.py`)."""
    parts = module[:-3].split("/") if module.endswith(".py") else module.split("/")
    real = module_path(parts)
    return "adopted.kali." + (real if real is not None else module[:-3]).replace("/", ".")


#: What the index records. The comparison in `check()` uses exactly these, so an
#: extractor field the index does not carry cannot manufacture a false defect.
INDEX_KEYS = ("shard_id", "kind", "tree", "module", "class", "lines",
              "public_api", "unnamed", "path")


class AtlasUnavailable(RuntimeError):
    """The census this gate READS is absent or unreadable -- not drift.

    The atlas lives outside the repo (``~/yggdrasil_forest/atlas_kali-linux.json``,
    written by ``tools/domain_trees.py`` on the Kali lane), so a host that has
    never run that census cannot judge the stub surface at all. That state used to
    arrive as ``SystemExit`` -- exit 1, the same code as real drift -- so the only
    two available readings were "the stubs are wrong" and "the gate is broken",
    and the truthful third ("nothing was judged") had no way to be said. It is a
    separate exception so ``main`` can exit 2: could not perform the run.
    """


def read_atlas(path: Path) -> Dict:
    if not path.is_file():
        raise AtlasUnavailable("atlas not found: %s\n"
                               "Pass --atlas, or run tools/domain_trees.py on the Kali lane."
                               % path)
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise AtlasUnavailable("%s is not valid JSON: %s" % (path, exc))


def units(atlas: Dict) -> List[Dict]:
    """One entry per named class unit in the atlas, sorted for a stable diff."""
    modules = atlas.get("modules") or {}
    generated = str(atlas.get("generated_at", ""))[:10]
    out: List[Dict] = []
    for module_name in sorted(modules):
        meta = modules[module_name] or {}
        tree = str(meta.get("tree") or "(root)")
        lines = int(meta.get("lines") or 0)
        public_api = int(meta.get("public_api") or 0)
        stem = slug(module_name.replace("/", "_").replace(".py", ""))
        named = sorted(meta.get("top_classes") or [])
        for klass in named:
            out.append({
                "shard_id": "kali:%s#%s" % (module_name, klass),
                "kind": "class",
                "tree": tree,
                "module": module_name,
                "class": klass,
                "lines": lines,
                "public_api": public_api,
                "unnamed": 0,
                "path": "shards/%s/%s__%s.py" % (slug(tree), stem, slug(klass)),
            })
        total = int(meta.get("classes") or 0)
        if total > len(named):
            # The atlas lists at most six classes per module. Measured 2026-11-14
            # against atlas_kali-linux.json: 141 of 6 928 modules exceed the cap,
            # holding 520 classes between them (the previous parenthetical here
            # said "52 of 679", a reading of an atlas one tenth this size). Those
            # classes are in the tree and reachable from the module, but the atlas
            # never recorded their names, so they get one residual shard that
            # states the count instead of fabricated per-class stubs.
            #
            # This guard cannot fire when the census under-reports: a module the
            # census scores `classes: 0` that really defines nine yields NO shard
            # at all, and `check()` cannot see it because the index and the atlas
            # are read from the same census. Measured 2026-11-14: one such module
            # among the 603 with a vendored copy, CODEX/CORE/azazael_pygame.py
            # (census 0, source 9). Fixing it means re-censusing, not editing here.
            out.append({
                "shard_id": "kali:%s#module" % module_name,
                "kind": "module",
                "tree": tree,
                "module": module_name,
                "class": None,
                "lines": lines,
                "public_api": public_api,
                "unnamed": total - len(named),
                "path": "shards/%s/%s__module.py" % (slug(tree), stem),
            })
    # Kali carries both `SCRIPTS/` and `scripts/`, and Windows cannot hold both:
    # the first version of this tool wrote 1,131 shards and left 1,118 files, with
    # the lowercase tree silently overwriting the uppercase one. A collision gets
    # a content-addressed suffix instead of a shrug, and the count stays honest.
    seen = set()
    for entry in out:
        entry["generated"] = generated
        if entry["path"].lower() in seen:
            digest = hashlib.sha1(entry["shard_id"].encode("utf-8")).hexdigest()[:8]
            entry["path"] = entry["path"][:-3] + "__%s.py" % digest
        seen.add(entry["path"].lower())
    return out


_LINE_COUNT: Dict[str, int] = {}


def vendor_lines(module: Optional[str]) -> int:
    """How many lines the vendored source for `module` has, or 0 if unreadable.

    Only `ledger_units` asks, and only for a module the census does not describe:
    a minted stub has to say *something* true about the unit it stands for, and a
    line count read off the file the import will hit is true in a way the census'
    silence is not. Cached because `--write` and `--check` walk the same ids.
    """
    if not module:
        return 0
    if module not in _LINE_COUNT:
        try:
            with (VENDOR / module).open("r", encoding="utf-8", errors="replace") as handle:
                _LINE_COUNT[module] = sum(1 for _ in handle)
        except OSError:
            _LINE_COUNT[module] = 0
    return _LINE_COUNT[module]


def ledger_units(census: Sequence[Dict], atlas: Dict) -> List[Dict]:
    """One entry per wired id the census does not carry.

    The ledger and the atlas answer different questions. `WIRED.json` records what
    a human adopted, with the test that proves it; the atlas records what one
    `domain_trees.py` run saw on one day. Where the ledger names a unit the census
    omits, the unit is real -- measured 2026-11-16 over all 94 remaining ids: each
    resolves to a file under `adopted/kali/`, 79 are classes and 15 are the module
    itself -- and the party that is silent is the census. Refusing to give those
    ids a shard made `--check` fail on 94 rows that were correct, and made every
    `load()` unreachable for a unit the tree had already adopted.

    Minted entries carry `census: False` and their own `detail` sentence. Neither
    key is in ``INDEX_KEYS``: a consumer reads what a shard *is*, not which census
    happened to find it, and `check()` keeps deriving its advisory set from the
    census alone so the gap cannot disappear into its own repair.
    """
    modules = atlas.get("modules") or {}
    generated = str(atlas.get("generated_at", ""))[:10]
    known = {entry["shard_id"] for entry in census}
    seen = {entry["path"].lower() for entry in census}
    out: List[Dict] = []
    for shard_id in sorted(wired_registry()):
        if shard_id in known:
            continue
        prefix, _, rest = shard_id.partition(":")
        module, _, klass = rest.partition("#")
        if prefix != "kali" or not module or not klass:
            # A foreign or malformed id is what `check()` reports as unexplained;
            # minting a shard here would hand an unexplained claim an address and
            # turn the one hard problem into a green line.
            continue
        meta = modules.get(module) or {}
        parts = module[:-3].split("/") if module.endswith(".py") else module.split("/")
        real = real_case(parts)
        tree = str(meta.get("tree")
                   or (real.split("/")[0] if real and "/" in real else "(root)"))
        lines = int(meta.get("lines") or 0) or vendor_lines(real)
        public_api = int(meta.get("public_api") or 0)
        stem = slug(module.replace("/", "_").replace(".py", ""))
        reason = classify_unmatched(shard_id, modules)
        if klass == "module":
            kind, class_name, unnamed = "module", None, 0
            subject = "shards/%s/%s__module.py" % (slug(tree), stem)
            why = ("the module itself, wired by shards/WIRED.json; the census names "
                   "every class of it, so this shard addresses the module rather "
                   "than a residual count"
                   if reason == "redundant_residual" else
                   "the module itself, wired by shards/WIRED.json; the atlas "
                   "carries no module by this name")
        else:
            kind, class_name, unnamed = "class", klass, 0
            subject = "shards/%s/%s__%s.py" % (slug(tree), stem, slug(klass))
            why = ("class %s, wired by shards/WIRED.json; the census does not name "
                   "it, so this stub rests on the ledger and the vendored source "
                   "(%d lines)" % (klass, lines))
        path = subject
        if path.lower() in seen:
            digest = hashlib.sha1(shard_id.encode("utf-8")).hexdigest()[:8]
            path = subject[:-3] + "__%s.py" % digest
        seen.add(path.lower())
        out.append({
            "shard_id": shard_id,
            "kind": kind,
            "tree": tree,
            "module": module,
            "class": class_name,
            "lines": lines,
            "public_api": public_api,
            "unnamed": unnamed,
            "path": path,
            "generated": generated,
            "detail": why,
            "census": False,
        })
    return out


def surface(atlas: Dict, census: Optional[Sequence[Dict]] = None) -> List[Dict]:
    """The shard set this tool writes, checks and adopts.

    The census' units plus the ledger's uncensused ones. `census` is accepted so a
    caller that needs both halves does not pay for `units()` twice -- it walks the
    whole atlas.
    """
    census = units(atlas) if census is None else list(census)
    return census + ledger_units(census, atlas)


def render_index(entries: Sequence[Dict], atlas: Dict) -> str:
    #: A wired row carries its **target**: the dotted module its `load()` returns
    #: the unit from. `adopt_queue.check_shards` used to infer the owner from the
    #: path suffix `adopted/kali/<module>`, which cannot work for a row whose
    #: ledger entry declares a `dotted` -- the five AOA units wave at
    #: `adopted.aoa.event_bus`, so the inference found no owner at all and
    #: reported five correct shards as broken (measured 2026-11-16, 5 of 1,139).
    #: The ledger is the authority for the target; the index is where a consumer
    #: reads it instead of re-deriving the resolver.
    wired = wired_registry()
    rows = []
    for entry in entries:
        row = {key: entry[key] for key in INDEX_KEYS}
        claim = wired.get(entry["shard_id"])
        if claim is not None:
            declared = claim.get("dotted") if isinstance(claim, dict) else None
            row["target"] = declared or dotted(entry["module"])
        rows.append(row)
    payload = {
        "schema": SCHEMA,
        "note": ("Generated by Project_ELIZA/tools/shard_intake.py from the Kali atlas. "
                 "Every entry is a generated stub; a wired one also carries `target`, "
                 "the dotted module its load() returns the unit from. Regenerate, "
                 "never hand-edit."),
        "atlas": {
            "environment": "kali-linux",
            "generated_at": atlas.get("generated_at"),
            "root": atlas.get("root"),
            "trees": (atlas.get("totals") or {}).get("trees"),
        },
        "counts": {
            "shards": len(entries),
            "modules": len({entry["module"] for entry in entries}),
            "trees": sorted({entry["tree"] for entry in entries}),
        },
        "shards": rows,
    }
    return json.dumps(payload, indent=1, sort_keys=False) + "\n"


def write(entries: Sequence[Dict], atlas: Dict) -> Dict:
    written = 0
    # Adoption survives regeneration. WIRED.json is the ledger and it is never
    # rewritten here, so a --write that emitted WIRED = False for an adopted
    # shard would put the tree and the ledger into disagreement: measured
    # 2026-11-14, 1152 of 4085 stubs declare WIRED = True and every one of them
    # is listed in WIRED.json. Regeneration must reproduce that, not undo it.
    wired_ids = wired_registry()
    trees = {entry["tree"] for entry in entries}
    # Tree directories are generated wholesale: a shard that left the atlas must
    # not survive as an orphan file a reader can import.
    if SHARDS.exists():
        for child in SHARDS.iterdir():
            if child.is_dir():
                shutil.rmtree(child)
    for tree in trees:
        directory = SHARDS / slug(tree)
        directory.mkdir(parents=True, exist_ok=True)
        (directory / "__init__.py").write_text(
            '"""Intake stubs for the %s tree. Generated; see SHARD_INDEX.json."""\n'
            % tree, encoding="utf-8", newline="\n")
    for entry in entries:
        path = REPO / entry["path"]
        path.parent.mkdir(parents=True, exist_ok=True)
        #: A minted entry brings its own sentence, because the census sentence
        #: would be a claim the census never made -- "0 public API entries" for a
        #: module the atlas does not describe is not a measurement, it is the
        #: absence of one wearing the same clothes.
        minted = entry.get("census") is False
        if entry["kind"] == "class":
            subject = entry["class"]
            literal = repr(entry["class"])
            detail = entry.get("detail") or (
                "class %s, %d lines in the module, %d public API entries"
                % (entry["class"], entry["lines"], entry["public_api"]))
        else:
            subject = "the module itself" if minted else "module residual"
            literal = "None"
            detail = entry.get("detail") or (
                "%d classes the atlas does not name individually (it lists at "
                "most six per module); read the module, do not assume the six "
                "are the whole story" % entry["unnamed"])
        text = STUB.format(tree=entry["tree"], module=entry["module"],
                           subject=subject, detail=detail, literal=literal,
                           klasses=entry.get("unnamed", 0),
                           klass_literal=literal, unnamed=entry.get("unnamed", 0),
                           kind=entry["kind"], source=entry["module"],
                           lines=entry["lines"], public_api=entry["public_api"],
                           generated=entry["generated"], shard_id=entry["shard_id"],
                           wired="True" if entry["shard_id"] in wired_ids else "False")
        # An adopted shard keeps its `load()`: the ledger names the module it
        # waves at, and a row may carry an explicit `dotted` for a target the
        # path resolver cannot derive (the five AOA units wave at
        # `adopted.aoa.event_bus`, not at `adopted.kali.AOA.core.event_bus`).
        claim = wired_ids.get(entry["shard_id"])
        if claim is None:
            text += LOAD_REFUSE
        else:
            declared = claim.get("dotted") if isinstance(claim, dict) else None
            text += LOAD_ADOPTED.format(dotted=declared or dotted(entry["module"]))
        path.write_text(text, encoding="utf-8", newline="\n")
        written += 1
    INDEX.write_text(render_index(entries, atlas), encoding="utf-8", newline="\n")
    if not WIRED.is_file():
        # Written once and never regenerated: this is the adoption ledger, and a
        # --write that reset it would quietly un-adopt work that is in production.
        WIRED.write_text(json.dumps({
            "schema": SCHEMA,
            "note": ("Shard id -> {test, commit}. A shard listed here has been wired "
                     "into ELIZA behind its stub path; the test is the evidence. "
                     "Edit by hand, in the adopting commit."),
            "wired": {},
        }, indent=1) + "\n", encoding="utf-8", newline="\n")
    return {"written": written, "trees": len(trees), "index": str(INDEX)}


def wired_registry() -> Dict[str, Dict]:
    """Shard id -> {test, commit} for every shard a human has adopted."""
    if not WIRED.is_file():
        return {}
    try:
        data = json.loads(WIRED.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise SystemExit("%s is not valid JSON: %s" % (WIRED.name, exc))
    return data.get("wired") or {}


def _stub_problems(path: Path, entry: Dict, wired: Optional[Dict] = None) -> List[str]:
    problems: List[str] = []
    try:
        text = path.read_text(encoding="utf-8")
        tree = ast.parse(text)
    except (OSError, SyntaxError) as exc:
        return ["%s does not parse: %s" % (entry["path"], exc)]
    flags = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1:
            target = node.targets[0]
            if isinstance(target, ast.Name) and isinstance(node.value, ast.Constant):
                flags[target.id] = node.value.value
    if wired:
        # Adopted: the flag flips, and the refusual is no longer expected here.
        if flags.get("WIRED") is not True:
            problems.append("%s is listed as wired in WIRED.json but declares "
                            "WIRED = %r" % (entry["path"], flags.get("WIRED")))
    elif flags.get("WIRED") is not False:
        problems.append("%s does not declare WIRED = False" % entry["path"])
    if flags.get("SHARD_ID") != entry["shard_id"]:
        problems.append("%s declares SHARD_ID %r, index says %r"
                        % (entry["path"], flags.get("SHARD_ID"), entry["shard_id"]))
    if flags.get("CLASS_NAME") != entry["class"]:
        problems.append("%s declares CLASS_NAME %r, index says %r"
                        % (entry["path"], flags.get("CLASS_NAME"), entry["class"]))
    loader = [node for node in tree.body
              if isinstance(node, ast.FunctionDef) and node.name == "load"]
    if not loader:
        problems.append("%s has no load() to refuse with" % entry["path"])
    elif not wired and not any(isinstance(node, ast.Raise)
                               for node in ast.walk(loader[0])):
        problems.append("%s load() does not raise: a stub that returns is a fake"
                        % entry["path"])
    elif wired and any(isinstance(node, ast.Raise) for node in ast.walk(loader[0])):
        # The mirror of the rule above, and the reason it exists: a wired shard
        # whose `load()` raises is a shard that was adopted and then quietly
        # un-adopted by a regeneration. `--check` passes only when the tree and
        # the ledger agree about which one it is.
        problems.append("%s is listed as wired in WIRED.json but its load() raises"
                        % entry["path"])
    #: Only an UNWIRED stub is held to "imports nothing". That rule exists so a
    #: generated stub cannot smuggle a copy in behind a name -- it was never a
    #: ban on an adopted shard reaching its implementation, and applying it to
    #: wired shards made the documented adoption shape (implement in a module,
    #: point load() at it) impossible to pass. Measured 2026-11-03: both a
    #: deferred and a module-level import were refused for a wired shard.
    if not wired:
        imports = [node for node in ast.walk(tree)
                   if isinstance(node, (ast.Import, ast.ImportFrom))]
        for node in imports:
            names = [alias.name for alias in node.names] \
                if isinstance(node, ast.Import) else [node.module or ""]
            for name in names:
                if name.split(".")[0] not in ("", "__future__"):
                    problems.append("%s imports %r: a stub drags no dependencies"
                                    % (entry["path"], name))
    return problems


#: Why the census does not corroborate a wired id, stated as a fact about the
#: CENSUS rather than about the claim. Measured 2026-11-14: all 107 unmatched
#: ids in ``WIRED.json`` resolve to a real file AND a real symbol under
#: ``Project_ELIZA/adopted/kali/``, so the party that is silent is the atlas
#: (a point-in-time census from 2026-11-09), not the ledger. Reporting those 107
#: as defects made ``--check`` exit 1 permanently -- a gate that cannot pass is
#: a gate nobody reads, and the twenty-first real one would have arrived
#: indistinguishable from the 107 false ones.
ADVISORY_KINDS = {
    "redundant_residual": "the census now names every class of this module, so "
                          "its #module residual shard is no longer needed",
    "census_truncated": "the census records at most six classes per module and "
                        "this module has more, so the class may be one of the "
                        "unrecorded ones",
    "census_silent": "the census names every class of this module and omits "
                     "this one, while the vendored source has it",
    "module_absent": "the census carries no module by this name",
}


def classify_unmatched(shard_id: str, modules: Dict) -> str:
    """Which census fact leaves a wired id uncorroborated, or ``unclassified``.

    This answers "why does the atlas not contain it", never "is it wrong". A
    kind outside ``ADVISORY_KINDS`` means the classifier has no explanation for
    the id, and an unexplained id must stay a hard problem: inventing a bucket
    to absorb it would rebuild the lie this function exists to remove.
    """
    if "#" not in shard_id:
        return "unclassified"
    module, _, klass = shard_id.partition("#")
    module = module.split(":", 1)[1] if ":" in module else module
    meta = modules.get(module)
    if meta is None:
        return "module_absent"
    named = list(meta.get("top_classes") or [])
    total = int(meta.get("classes") or 0)
    if klass == "module":
        # A residual id is minted only while the module has unrecorded classes;
        # if the census now names them all, `units()` stops minting it.
        return "redundant_residual" if total <= len(named) else "unclassified"
    if klass in named:
        # The id SHOULD have matched. It did not, so something other than the
        # census cap is at work and this classifier cannot name it.
        return "unclassified"
    return "census_truncated" if total > len(named) else "census_silent"


def check(atlas: Dict, strict: bool = False) -> Tuple[bool, List[str], Dict]:
    """Two tiers: defects fail always, census mismatches fail only under strict.

    ``strict`` is keyword-only-with-default because a caller outside this module
    unpacks the 3-tuple (``Project_ELIZA/tests/test_shard_intake.py:66``).
    """
    problems: List[str] = []
    advisories: List[str] = []
    buckets: Dict[str, int] = {}
    modules_by_name = atlas.get("modules") or {}
    assigned = wired_registry()
    if not INDEX.is_file():
        return False, ["%s is absent; run --write" % INDEX.relative_to(REPO)], {}
    index = json.loads(INDEX.read_text(encoding="utf-8"))
    on_disk = {entry["path"]: {key: entry.get(key) for key in INDEX_KEYS}
               for entry in index.get("shards", [])}
    census = units(atlas)
    #: The whole surface, not just the census. A wired id the atlas is silent
    #: about is still a real shard -- `ledger_units` mints it -- so judging the
    #: index against the census alone reported all 94 of those stubs as
    #: "in the index but not the atlas (stale stub)" on every run.
    entries = surface(atlas, census)
    expected = {entry["path"]: {key: entry[key] for key in INDEX_KEYS}
                for entry in entries}
    for path in sorted(set(expected) - set(on_disk)):
        problems.append("%s is in the atlas but not the index" % path)
    for path in sorted(set(on_disk) - set(expected)):
        problems.append("%s is in the index but not the atlas (stale stub)" % path)
    for path in sorted(set(on_disk) & set(expected)):
        if on_disk[path] != expected[path]:
            problems.append("%s disagrees with the atlas: index %r, atlas %r"
                            % (path, on_disk[path], expected[path]))
    for entry in index.get("shards", []):
        file_path = REPO / entry["path"]
        if not file_path.is_file():
            problems.append("%s is indexed but absent" % entry["path"])
            continue
        problems.extend(_stub_problems(file_path, entry,
                                       assigned.get(entry["shard_id"])))
    #: The surface index above is keyed by PATH; a ledger entry is an ID.
    #: Comparing the id to that dict reported every wired shard as "not in the
    #: atlas", which no gate run could catch while the ledger was empty -- the
    #: first adoption exercised the branch (measured 2026-11-03: five real ids,
    #: five false defects).
    unit_ids = {entry["shard_id"] for entry in census}
    for shard_id, claim in sorted(assigned.items()):
        if shard_id not in unit_ids:
            kind = classify_unmatched(shard_id, modules_by_name)
            if kind not in ADVISORY_KINDS:
                problems.append("WIRED.json names %r, which is not in the atlas and "
                                "no census fact explains it" % shard_id)
                continue
            buckets[kind] = buckets.get(kind, 0) + 1
            advisories.append("%s: %s -- %s" % (kind, shard_id, ADVISORY_KINDS[kind]))
            #: Deliberately NOT a `continue`. The control check used to sit
            #: behind one, so every id the census did not corroborate went
            #: unvalidated -- 107 of 1,152 adopted claims were a claim with no
            #: check, which is the one thing this function exists to refuse.
        test = claim.get("test") if isinstance(claim, dict) else None
        if not isinstance(test, str) or not test.strip():
            problems.append("WIRED.json entry %r names no test: a wired shard is a "
                            "claim, and a claim needs a control" % shard_id)
        elif not (REPO / test).is_file():
            problems.append("WIRED.json entry %r names %r, which does not exist"
                            % (shard_id, test))
    stray = [p for p in SHARDS.rglob("*.py")
             if p.name != "__init__.py"
             and str(p.relative_to(REPO)).replace("\\", "/") not in expected]
    for path in sorted(stray):
        problems.append("%s is not in the atlas: an adopted shard must be wired "
                        "deliberately, not left as a generated file"
                        % path.relative_to(REPO))
    counts = index.get("counts", {})
    if counts.get("shards") != len(expected):
        problems.append("index claims %r shards; the atlas yields %d"
                        % (counts.get("shards"), len(expected)))
    if strict:
        # Promoted, not dropped: `--strict` is how a caller says it wants the
        # census mismatches to fail too. Default stays advisory for HED-2's
        # reason -- a gate red on the day it lands is a gate switched off.
        problems.extend(advisories)
        advisories = []
    return (not problems), problems, {"shards": len(expected),
                                      "modules": len({e["module"] for e in expected.values()}),
                                      "trees": len({e["tree"] for e in expected.values()}),
                                      "wired": len(assigned),
                                      "advisory_lines": advisories,
                                      "buckets": buckets}


def adopt(shard_id: str, atlas: Dict) -> int:
    entries = {entry["shard_id"]: entry for entry in surface(atlas)}
    entry = entries.get(shard_id)
    if entry is None:
        close = [key for key in entries if shard_id.lower() in key.lower()][:5]
        print("no shard %r in the atlas" % shard_id, file=sys.stderr)
        if close:
            print("closest: " + ", ".join(close), file=sys.stderr)
        return 1
    print("Adopt plan for %s" % shard_id)
    print("  source   kali-linux %s (%s)"
          % (entry["module"],
             "class %s" % entry["class"] if entry["class"] else "the module itself"))
    print("  stub     %s" % entry["path"])
    print("  steps")
    print("    1. read the Kali source; list its imports and its side effects")
    print("    2. write a test in Project_ELIZA/tests/ that fails for the right reason")
    print("    3. implement behind the same module path and set WIRED = True")
    print("    4. add the shard id to shards/WIRED.json: {\"test\": <path>, "
          "\"commit\": <sha>}")
    print("    5. python tools/shard_intake.py --check   (stub drift, then wired drift)")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--atlas", default=str(DEFAULT_ATLAS))
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--strict", action="store_true",
                        help="with --check, fail on census mismatches as well")
    parser.add_argument("--list", action="store_true")
    parser.add_argument("--tree", help="limit --list to one tree")
    parser.add_argument("--adopt", metavar="SHARD_ID")
    args = parser.parse_args(argv)

    # Exit 2, not 1: `2` means "the run could not be performed", which is neither
    # a pass nor a verdict on the tree. Collapsing it into 1 let a missing input
    # read as a drifted surface, and the commit gate would then refuse a healthy
    # tree for a reason that has nothing to do with the tree.
    try:
        atlas = read_atlas(Path(args.atlas))
    except AtlasUnavailable as exc:
        print("CANNOT JUDGE: %s" % exc, file=sys.stderr)
        return 2
    entries = surface(atlas)

    if args.write:
        result = write(entries, atlas)
        print("wrote %(written)d stub(s) across %(trees)d tree(s); index %(index)s"
              % result)
        return 0
    if args.check:
        ok, problems, counts = check(atlas, strict=args.strict)
        for problem in problems:
            print("DEFECT: " + problem)
        for line in counts.get("advisory_lines", []):
            print("ADVISORY: " + line)
        print("%s -- %d shard(s), %d module(s) yielding units, %d tree(s), %d wired"
              % ("clean" if ok else "%d defect(s)" % len(problems),
                 counts.get("shards", 0), counts.get("modules", 0),
                 counts.get("trees", 0), counts.get("wired", 0)))
        buckets = counts.get("buckets") or {}
        if buckets:
            print("  uncorroborated by the census, with the reason: " +
                  ", ".join("%s=%d" % (key, buckets[key]) for key in sorted(buckets)))
        return 0 if ok else 1
    if args.adopt:
        return adopt(args.adopt, atlas)
    grouped: Dict[str, int] = {}
    for entry in entries:
        grouped[entry["tree"]] = grouped.get(entry["tree"], 0) + 1
    for tree in sorted(grouped):
        if args.tree and tree != args.tree:
            continue
        print("%-24s %4d shard(s)" % (tree, grouped[tree]))
    print("%-24s %4d" % ("total", len(entries)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
