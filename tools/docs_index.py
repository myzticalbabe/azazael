#!/usr/bin/env python3
"""docs_index.py — generate docs/INDEX.md from path + first heading + date.

No hand maintenance: re-run to regenerate. Output is deterministic: rows are
sorted by path and ``Modified`` is the file's last commit date, not its mtime, so
two checkouts of one commit produce the same bytes. (A wall-clock header and an
mtime column both used to churn this file on every run.)

Usage:
    python docs_index.py [--root docs/] [--out docs/INDEX.md]
"""
from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"


def first_heading(path: Path) -> str:
    """Extract the first markdown heading from a file."""
    try:
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            m = re.match(r"^#{1,6}\s+(.+)$", line.strip())
            if m:
                return m.group(1).strip()
    except OSError as exc:
        note_failure("tools/docs_index.py", exc)
        pass
    return "(no heading)"


def git_dates() -> dict[str, str]:
    """Map repo-relative path -> last commit date (YYYY-MM-DD) in ONE git pass.

    mtime is a property of this checkout, not of the tree: a clone or a touch
    rewrites every row. A commit date is a property of the content, so the index
    is reproducible. An empty mapping means git could not be read; the caller
    says so in the output instead of passing guesses off as dates.
    """
    try:
        proc = subprocess.run(
            ["git", "-C", str(ROOT), "log", "--diff-filter=AM",
             "--name-only", "--pretty=format:%x1f%cs", "--", "."],
            capture_output=True, text=True, encoding="utf-8",
            errors="replace", timeout=120,
        )
    except (OSError, subprocess.SubprocessError) as exc:
        note_failure("tools/docs_index.py:git", exc)
        return {}
    if proc.returncode != 0:
        note_failure(
            "tools/docs_index.py:git",
            RuntimeError("git log exit %d: %s" % (
                proc.returncode, proc.stderr.strip()[:200])),
        )
        return {}
    dates: dict[str, str] = {}
    current = ""
    # Split on "\n" and check the marker BEFORE any strip(): str.strip() treats
    # \x1c-\x1f as whitespace, so line.strip() silently eats the \x1f record
    # marker and the whole log parses as zero dates (measured). HED-12 records
    # the same strip() trap eating the leading space of git porcelain output.
    for line in proc.stdout.split("\n"):
        line = line.rstrip("\r")
        if not line:
            continue
        if line[0] == "\x1f":
            current = line[1:].strip()
        elif current:
            dates.setdefault(line, current)       # newest commit wins
    return dates


def generate_index(docs_dir: Path, dates: dict[str, str]) -> str:
    """Generate a markdown index of all .md files under docs_dir."""
    md_files = sorted(docs_dir.rglob("*.md"))
    lines = [
        "# Documentation Index",
        "",
        "Generated by `tools/docs_index.py`. `Modified` is the last commit date, so",
        "re-running on the same tree yields the same bytes.",
        "",
        f"**{len(md_files)} documents**",
    ]
    if not dates:
        lines += [
            "",
            "**Dates unreadable** — `git log` could not be read, so every `Modified`",
            "below reads `unknown`. That is a blind reading, not an empty history.",
        ]
    lines += ["", "| Path | First heading | Modified |", "|---|---|---|"]
    for f in md_files:
        rel = f.relative_to(docs_dir.parent).as_posix()
        heading = first_heading(f)
        try:
            key = f.resolve().relative_to(ROOT).as_posix()
        except ValueError:                         # --root outside this repo
            key = rel
        if not dates:
            date = "unknown"
        else:
            date = dates.get(rel) or dates.get(key) or "untracked"
        lines.append(f"| `{rel}` | {heading} | {date} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(DOCS), help="docs directory")
    ap.add_argument("--out", default=str(DOCS / "INDEX.md"), help="output file")
    args = ap.parse_args()

    docs_dir = Path(args.root).resolve()
    if not docs_dir.is_dir():
        print(f"error: {docs_dir} is not a directory", file=__import__("sys").stderr)
        return 2

    index = generate_index(docs_dir, git_dates())
    out_path = Path(args.out).resolve()
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(index, encoding="utf-8")
    print(f"Wrote {index.count(chr(10))} lines to {out_path}")
    return 0


