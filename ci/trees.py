"""One CI fork per tree, derived from the tracked tree instead of typed by hand.

The request is that every tree and sub-tree gets CI.  Sixty-four hand-written
workflow files would satisfy that on the day they were written and rot on the
next commit that adds a project, so the fork set is *generated*:

  ci/trees.json      the committed registry -- which trees are CI targets
  .github/workflows/trees.yml   one matrix job per registry entry

This script owns the registry.  It reads `git ls-files`, so a tree exists here
exactly when it holds a tracked Python file, and `--check` fails when the
committed registry and the tree disagree.  That is the only thing that stops
the CI surface from silently missing the next project.

What is NOT a target, and why, is printed and committed rather than hidden:
historical trees, build output and vendored binaries are named in `EXCLUDED`.

  python ci/trees.py --write     # regenerate ci/trees.json
  python ci/trees.py --check     # exit 1 when the registry is stale
  python ci/trees.py --matrix    # GitHub Actions matrix json on stdout
  python ci/trees.py             # print the plan
"""
import json
import subprocess
import sys
from pathlib import Path

SCHEMA = 1
LIST_TIMEOUT = 120
HERE = Path(__file__).resolve().parent
REGISTRY = HERE / "trees.json"

#: Trees that are never CI targets, each with the reason it is not one.
EXCLUDED = {
    "archive": "historical snapshot",
    "archived": "historical snapshot",
    "archived_unified": "historical snapshot",
    "nuitka_build_backup": "build backup",
    "temp": "scratch",
    "skills_staging": "staging copy",
    "build": "build output",
    "dist": "build output",
    "dist-native": "build output",
    "__pycache__": "compiled cache",
    "chromedriver-win64": "vendored binary",
    "docker": "container recipe",
}

#: Container directories whose children are the real projects.  A job for
#: `src` alone would report 70 roots in one log, so the fork is taken one
#: level deeper when `--depth 2` is asked for; the default stays at the
#: top level because that is the unit a reader recognises.
CONTAINERS = ("src", "packages")


def listing(repo):
    """Tracked paths, or None when git cannot answer."""
    try:
        done = subprocess.run(
            ["git", "ls-files"], cwd=str(repo), timeout=LIST_TIMEOUT,
            capture_output=True, text=True, encoding="utf-8", errors="replace",
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        print("trees: BLIND -- git ls-files failed: %s" % exc)
        return None
    if done.returncode != 0:
        print("trees: BLIND -- git ls-files rc=%d" % done.returncode)
        return None
    return done.stdout.splitlines()


def discover(repo, depth=1):
    """Every tree holding tracked Python, with whether it owns tests."""
    tracked = listing(repo)
    if tracked is None:
        return None
    files = [p for p in tracked if p]
    trees = {}
    for rel in files:
        if not rel.endswith(".py"):
            continue
        parts = rel.split("/")
        if len(parts) == 1:
            continue  # a loose root file belongs to no tree
        name = parts[0]
        if name in EXCLUDED:
            continue
        if depth > 1 and name in CONTAINERS and len(parts) > 2:
            name = "/".join(parts[:2])
        row = trees.setdefault(name, {"name": name, "py": 0, "tests": 0})
        row["py"] += 1
        # A suite is a *test module*, not any file that lives under a tests
        # directory: counting `tests/helpers.py` as a test made every tree
        # with a fixture module look like it owned a runnable suite.
        stem = parts[-1][:-3]
        if stem.startswith("test_") or stem.endswith("_test"):
            row["tests"] += 1
    return {
        "schema": SCHEMA,
        "note": "generated by ci/trees.py --write; edit the generator, not this file",
        "excluded": EXCLUDED,
        "trees": [trees[n] for n in sorted(trees)],
    }


def matrix(plan):
    """The GitHub Actions matrix: one include entry per tree."""
    return {"include": [
        {"tree": t["name"], "tests": t["tests"]}
        for t in plan["trees"]
    ]}


def compare(saved, plan):
    """Structural differences only.

    Counts are deliberately not compared: a commit that adds a file would
    otherwise fail CI and teach the reader to ignore the check.  A tree that
    appears or disappears is a real change to the CI surface, and so is a
    tree that grew a test suite, because that is what turns its job from a
    compile check into a test run.
    """
    old = {t["name"]: t.get("tests", 0) for t in saved.get("trees", [])}
    new = {t["name"]: t["tests"] for t in plan["trees"]}
    fresh = sorted(set(new) - set(old))
    gone = sorted(set(old) - set(new))
    grown = sorted(n for n in set(new) & set(old)
                   if bool(old[n]) != bool(new[n]))
    return fresh, gone, grown


def write(plan):
    REGISTRY.write_text(json.dumps(plan, indent=1, sort_keys=True) + "\n",
                        encoding="utf-8")
    print("trees: wrote %s -- %d tree(s), %d excluded"
          % (REGISTRY.name, len(plan["trees"]), len(plan["excluded"])))


def main(argv):
    repo = HERE.parent
    depth = 1
    if "--depth" in argv:
        index = argv.index("--depth")
        if index + 1 < len(argv) and argv[index + 1] == "2":
            depth = 2
    plan = discover(repo, depth)
    if plan is None:
        return 2

    if "--matrix" in argv:
        print(json.dumps(matrix(plan)))
        return 0

    if "--write" in argv:
        write(plan)
        return 0

    if "--check" in argv:
        if not REGISTRY.exists():
            print("trees: FAIL -- %s is absent; run --write" % REGISTRY.name)
            return 1
        try:
            saved = json.loads(REGISTRY.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            print("trees: FAIL -- %s unreadable: %s" % (REGISTRY.name, exc))
            return 1
        if saved.get("schema") != SCHEMA:
            print("trees: FAIL -- registry schema %r, generator is %d"
                  % (saved.get("schema"), SCHEMA))
            return 1
        fresh, gone, grown = compare(saved, plan)
        if fresh or gone or grown:
            for name in fresh:
                print("trees: MISSING from registry -- %s" % name)
            for name in gone:
                print("trees: STALE in registry -- %s no longer holds Python"
                      % name)
            for name in grown:
                print("trees: TEST SET CHANGED -- %s" % name)
            print("trees: FAIL -- run `python ci/trees.py --write` and commit %s"
                  % REGISTRY.name)
            return 1
        print("trees: PASS -- registry matches the tracked tree (%d tree(s), "
              "%d excluded)" % (len(plan["trees"]), len(plan["excluded"])))
        return 0

    print("trees: %d CI target(s), %d excluded"
          % (len(plan["trees"]), len(plan["excluded"])))
    for tree in plan["trees"]:
        print("  %-38s %5d py  %4d test file(s)%s"
              % (tree["name"], tree["py"], tree["tests"],
                 "" if tree["tests"] else "  (no suite)"))
    print("\nexcluded:")
    for name in sorted(plan["excluded"]):
        print("  %-38s %s" % (name, plan["excluded"][name]))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
