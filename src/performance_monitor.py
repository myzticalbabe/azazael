"""
PerformanceMonitor — Cross-Project System Monitoring
=====================================================
Centralized performance monitoring for all AZAZAEL projects.

Aggregates metrics from multiple sources:
- psutil-based CPU, memory, disk, I/O stats
- Process-level resource tracking (RSS, CPU%, threads)
- WAL/journal monitoring for SQLite DBs
- HTTP endpoint health checks (Ollama, llama-server, openmono)
- Goroutine/thread pool monitoring
- Graceful degradation when optional dependencies are missing

Previously, performance monitoring was scattered across 6+ subsystems:
  - azazael_wsa.py (per-subsystem psutil snapshots)
  - HYDRA_CLUSTER Phase 6 / FEEDBACK
  - WORMZ_EXECUTION I/O monitoring
  - openmono.ai/scripts/perf_logs/ echo*.perf_log
  - llama-server --metrics flag
  - Docker compose health checks

This module unifies them all into a single monitoring interface.

Usage:
    >>> from performance_monitor import PerformanceMonitor
    >>> pm = PerformanceMonitor()
    >>> snapshot = pm.capture()
    >>> print(pm.format_summary(snapshot))
"""

import json
import time
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path
from typing import Any

# ── Optional dependencies (graceful degradation) ────────────────────

try:
    import psutil
    HAS_PSUTIL = True
except ImportError:
    psutil = None  # type: ignore
    HAS_PSUTIL = False

try:
    import sqlite3 as _sqlite
    HAS_SQLITE = True
except ImportError:
    HAS_SQLITE = False

try:
    import requests as _requests
    HAS_REQUESTS = True
except ImportError:
    HAS_REQUESTS = False


# ── Data Types ───────────────────────────────────────────────────────

@dataclass
class Alert:
    """An alert generated by threshold evaluation."""
    level: str = "info"  # "info", "warning", "critical"
    metric: str = ""
    message: str = ""
    value: float = 0.0
    threshold: float = 0.0


@dataclass
class SystemSnapshot:
    """A point-in-time capture of system resource usage."""
    timestamp: str = field(default_factory=lambda: datetime.now().isoformat())
    cpu_percent: float = 0.0
    cpu_count: int = 1
    memory_total_gb: float = 0.0
    memory_used_gb: float = 0.0
    memory_percent: float = 0.0
    swap_used_gb: float = 0.0
    disk_used_percent: float = 0.0
    disk_free_gb: float = 0.0
    io_read_mb: float = 0.0
    io_write_mb: float = 0.0
    network_sent_mb: float = 0.0
    network_recv_mb: float = 0.0
    process_count: int = 0


@dataclass
class ProcessSnapshot:
    """Resource usage of a specific process."""
    pid: int = 0
    name: str = ""
    cpu_percent: float = 0.0
    memory_rss_mb: float = 0.0
    memory_vms_mb: float = 0.0
    threads: int = 0
    open_files: int = 0
    uptime_seconds: float = 0.0


@dataclass
class DBHealthSnapshot:
    """Health of a SQLite database."""
    path: str = ""
    size_mb: float = 0.0
    wal_size_mb: float = 0.0
    integrity: str = "unknown"
    page_count: int = 0
    freelist_count: int = 0
    schema_version: str = "unknown"


@dataclass
class ServiceHealth:
    """Health check result for a service endpoint."""
    name: str = ""
    url: str = ""
    reachable: bool = False
    status_code: int = 0
    latency_ms: float = 0.0
    version: str = ""
    error: str = ""


# ── Main Monitor ─────────────────────────────────────────────────────

class PerformanceMonitor:
    """Centralized performance monitoring across all projects.

    Usage:
        pm = PerformanceMonitor()
        snap = pm.capture()          # Full system + process + DB + service snapshot
        pm.print_snapshot(snap)      # Human-readable
        pm.save_snapshot(snap, "snapshots/snap_001.json")  # Persist
    """

    # Default services to health-check
    DEFAULT_SERVICES = [
        ("ollama", "http://localhost:11434/"),
        ("llama-server", "http://localhost:8080/health"),
        ("openmono-rust", "http://localhost:9090/health"),
        ("openmono-go", "http://localhost:9091/health"),
    ]

    # Default DBs to monitor
    DEFAULT_DBS = [
        "workspace/session_memory.db",
        "workspace/graph.db",
    ]

    # Processes of interest (name keywords)
    WATCHED_PROCESSES = [
        "python", "ollama", "llama-server", "openmono", "go-bridge",
        "rust-bindings", "node", "docker",
    ]

    def __init__(self, db_paths: (list[str] | None) = None,
                 services: (list[tuple[str, str]] | None) = None):
        self.db_paths = db_paths or self.DEFAULT_DBS
        self.services = services or self.DEFAULT_SERVICES

    # ── System Metrics ──────────────────────────────────────────

    def capture_system(self) -> SystemSnapshot:
        """Capture system-level resource metrics."""
        snap = SystemSnapshot()

        if not HAS_PSUTIL:
            return snap

        try:
            snap.cpu_percent = psutil.cpu_percent(interval=0.1)
            snap.cpu_count = psutil.cpu_count() or 1
            mem = psutil.virtual_memory()
            snap.memory_total_gb = round(mem.total / (1024 ** 3), 2)
            snap.memory_used_gb = round(mem.used / (1024 ** 3), 2)
            snap.memory_percent = mem.percent
            swap = psutil.swap_memory()
            snap.swap_used_gb = round(swap.used / (1024 ** 3), 2)
            disk = psutil.disk_usage("/")
            snap.disk_used_percent = disk.percent
            snap.disk_free_gb = round(disk.free / (1024 ** 3), 2)

            io_counters = psutil.disk_io_counters()
            if io_counters:
                snap.io_read_mb = round(io_counters.read_bytes / (1024 ** 2), 2)
                snap.io_write_mb = round(io_counters.write_bytes / (1024 ** 2), 2)

            net_io = psutil.net_io_counters()
            if net_io:
                snap.network_sent_mb = round(net_io.bytes_sent / (1024 ** 2), 2)
                snap.network_recv_mb = round(net_io.bytes_recv / (1024 ** 2), 2)

            snap.process_count = len(psutil.pids())
        except Exception:
            pass  # Graceful degradation

        return snap

    # ── Process Metrics ─────────────────────────────────────────

    def capture_watched_processes(self) -> list[ProcessSnapshot]:
        """Capture resource usage for all watched processes."""
        if not HAS_PSUTIL:
            return []

        snapshots = []
        try:
            for proc in psutil.process_iter(["pid", "name", "cpu_percent",
                                              "memory_info", "num_threads",
                                              "open_files", "create_time"]):
                try:
                    info = proc.info
                    name = info["name"] or ""
                    if not any(kw.lower() in name.lower()
                              for kw in self.WATCHED_PROCESSES):
                        continue

                    mem = info["memory_info"]
                    psnap = ProcessSnapshot(
                        pid=info["pid"] or 0,
                        name=name,
                        cpu_percent=info["cpu_percent"] or 0.0,
                        memory_rss_mb=round((mem.rss if mem else 0) / (1024 ** 2), 2),
                        memory_vms_mb=round((mem.vms if mem else 0) / (1024 ** 2), 2),
                        threads=info["num_threads"] or 0,
                        open_files=len(info["open_files"] or []),
                        uptime_seconds=round(time.time() - (info["create_time"] or time.time()), 0),
                    )
                    snapshots.append(psnap)
                except (psutil.NoSuchProcess, psutil.AccessDenied):
                    continue
        except Exception:
            pass

        return sorted(snapshots, key=lambda s: s.memory_rss_mb, reverse=True)

    # ── Database Health ─────────────────────────────────────────

    def capture_db_health(self) -> list[DBHealthSnapshot]:
        """Check health of all monitored SQLite databases."""
        if not HAS_SQLITE:
            return []

        snapshots = []
        for db_path in self.db_paths:
            path = Path(db_path)
            if not path.exists():
                continue

            try:
                conn = _sqlite.connect(str(path))
                try:
                    size_mb = path.stat().st_size / (1024 ** 2)

                    wal_path = Path(str(path) + "-wal")
                    wal_size_mb = (wal_path.stat().st_size / (1024 ** 2)
                                   if wal_path.exists() else 0.0)

                    integrity = conn.execute("PRAGMA integrity_check").fetchone()
                    page_count = conn.execute("PRAGMA page_count").fetchone()
                    freelist = conn.execute("PRAGMA freelist_count").fetchone()
                    # Not all DBs have a metadata table — fall back gracefully
                    try:
                        schema_ver = conn.execute(
                            "SELECT value FROM metadata WHERE key='schema_version'"
                        ).fetchone()
                    except Exception:
                        schema_ver = None

                    snap = DBHealthSnapshot(
                        path=str(path),
                        size_mb=round(size_mb, 2),
                        wal_size_mb=round(wal_size_mb, 2),
                        integrity=str(integrity[0]) if integrity else "unknown",
                        page_count=page_count[0] if page_count else 0,
                        freelist_count=freelist[0] if freelist else 0,
                        schema_version=schema_ver[0] if schema_ver else "unknown",
                    )
                    snapshots.append(snap)
                finally:
                    conn.close()
            except Exception:
                pass

        return snapshots

    # ── Service Health ──────────────────────────────────────────

    def capture_service_health(self) -> list[ServiceHealth]:
        """Health-check all monitored services."""
        if not HAS_REQUESTS:
            return [ServiceHealth(
                name=name, url=url, reachable=False,
                error="requests not installed"
            ) for name, url in self.services]

        results = []
        for name, url in self.services:
            try:
                start = time.perf_counter()
                resp = _requests.get(url, timeout=5)
                latency = (time.perf_counter() - start) * 1000

                version = ""
                try:
                    body = resp.json()
                    if isinstance(body, dict):
                        version = body.get("version", "")
                except Exception:
                    pass

                results.append(ServiceHealth(
                    name=name, url=url, reachable=True,
                    status_code=resp.status_code,
                    latency_ms=round(latency, 1),
                    version=version,
                ))
            except Exception as e:
                results.append(ServiceHealth(
                    name=name, url=url, reachable=False,
                    error=str(e)[:200],
                ))

        return results

    # ── Alerting Thresholds ────────────────────────────────────

    CPU_CRITICAL = 90.0
    MEMORY_WARNING = 80.0
    MEMORY_CRITICAL = 90.0
    DB_SIZE_WARNING_MB = 100.0

    def evaluate_alerts(self, snapshot: dict[str, Any]) -> list[Alert]:
        """Evaluate thresholds against a snapshot and return triggered alerts."""
        alerts = []
        sys_info = snapshot.get("system", {})
        dbs = snapshot.get("databases", [])

        # CPU
        cpu = sys_info.get("cpu_percent", 0)
        if cpu >= self.CPU_CRITICAL:
            alerts.append(Alert(
                level="critical", metric="cpu_percent",
                message=f"CPU at {cpu:.1f}% — exceeds critical threshold of {self.CPU_CRITICAL}%",
                value=cpu, threshold=self.CPU_CRITICAL,
            ))

        # Memory
        mem = sys_info.get("memory_percent", 0)
        if mem >= self.MEMORY_CRITICAL:
            alerts.append(Alert(
                level="critical", metric="memory_percent",
                message=f"Memory at {mem:.1f}% — exceeds critical threshold of {self.MEMORY_CRITICAL}%",
                value=mem, threshold=self.MEMORY_CRITICAL,
            ))
        elif mem >= self.MEMORY_WARNING:
            alerts.append(Alert(
                level="warning", metric="memory_percent",
                message=f"Memory at {mem:.1f}% — exceeds warning threshold of {self.MEMORY_WARNING}%",
                value=mem, threshold=self.MEMORY_WARNING,
            ))

        # Database sizes
        for d in dbs:
            size = d.get("size_mb", 0)
            if size >= self.DB_SIZE_WARNING_MB:
                alerts.append(Alert(
                    level="warning", metric="db_size",
                    message=f"Database {d.get('path', '?')} at {size:.1f} MB exceeds {self.DB_SIZE_WARNING_MB} MB warning threshold",
                    value=size, threshold=self.DB_SIZE_WARNING_MB,
                ))

        return alerts

    # ── Full Capture ────────────────────────────────────────────

    def capture(self) -> dict[str, Any]:
        """Full capture: system + processes + DBs + services + alerts."""
        snapshot = {
            "captured_at": datetime.now().isoformat(),
            "system": self._snapshot_to_dict(self.capture_system()),
            "processes": [self._snapshot_to_dict(p)
                         for p in self.capture_watched_processes()],
            "databases": [self._snapshot_to_dict(d)
                         for d in self.capture_db_health()],
            "services": [self._snapshot_to_dict(s)
                        for s in self.capture_service_health()],
        }
        snapshot["alerts"] = [self._snapshot_to_dict(a)
                              for a in self.evaluate_alerts(snapshot)]
        return snapshot

    # ── Formatting ──────────────────────────────────────────────

    def format_summary(self, snapshot: dict[str, Any]) -> str:
        """Format a capture snapshot as a human-readable summary."""
        sys_info = snapshot.get("system", {})
        procs = snapshot.get("processes", [])
        dbs = snapshot.get("databases", [])
        svcs = snapshot.get("services", [])

        lines = []
        lines.append("=" * 60)
        lines.append(f"  PERFORMANCE SNAPSHOT — {snapshot.get('captured_at', '?')}")
        lines.append("=" * 60)

        if sys_info:
            lines.append("\n  System:")
            lines.append(f"    CPU: {sys_info.get('cpu_percent', 0):.1f}% "
                        f"({sys_info.get('cpu_count', 1)} cores)")
            lines.append(f"    Memory: {sys_info.get('memory_used_gb', 0):.1f} / "
                        f"{sys_info.get('memory_total_gb', 0):.1f} GB "
                        f"({sys_info.get('memory_percent', 0):.1f}%)")
            lines.append(f"    Disk: {sys_info.get('disk_used_percent', 0):.1f}% used, "
                        f"{sys_info.get('disk_free_gb', 0):.1f} GB free")
            lines.append(f"    Processes: {sys_info.get('process_count', 0)}")

        if procs:
            lines.append(f"\n  Watched Processes ({len(procs)}):")
            for p in procs[:8]:
                lines.append(
                    f"    {p['name']:20s}  PID {p['pid']:>6d}  "
                    f"CPU {p.get('cpu_percent', 0):5.1f}%  "
                    f"RSS {p.get('memory_rss_mb', 0):7.1f} MB  "
                    f"{p.get('threads', 0)} threads"
                )

        if dbs:
            lines.append(f"\n  Databases ({len(dbs)}):")
            for d in dbs:
                status = "✓" if d.get("integrity") == "ok" else "✗"
                lines.append(
                    f"    {status} {d['path']:40s}  "
                    f"{d.get('size_mb', 0):5.1f} MB  "
                    f"WAL {d.get('wal_size_mb', 0):5.1f} MB"
                )

        if svcs:
            lines.append(f"\n  Services ({len(svcs)}):")
            for s in svcs:
                if s.get("reachable"):
                    lines.append(
                        f"    ✓ {s['name']:20s}  "
                        f"{s.get('latency_ms', 0):5.1f} ms  "
                        f"v{s.get('version', '?')}"
                    )
                else:
                    lines.append(
                        f"    ✗ {s['name']:20s}  "
                        f"unreachable: {s.get('error', '?')[:40]}"
                    )

        lines.append("\n" + "=" * 60)
        return "\n".join(lines)

    def print_snapshot(self, snapshot: (dict[str, Any] | None) = None):
        """Capture (if needed) and print a snapshot."""
        if snapshot is None:
            snapshot = self.capture()
        print(self.format_summary(snapshot))

    # ── Persistence ─────────────────────────────────────────────

    def save_snapshot(self, snapshot: dict[str, Any], filepath: str):
        """Save a snapshot to a JSON file."""
        path = Path(filepath)
        path.parent.mkdir(parents=True, exist_ok=True)
        with open(path, "w") as f:
            json.dump(snapshot, f, indent=2)

    def load_snapshot(self, filepath: str) -> dict[str, Any]:
        """Load a snapshot from a JSON file."""
        with open(filepath) as f:
            return json.load(f)

    # ── Helpers ─────────────────────────────────────────────────

    @staticmethod
    def _snapshot_to_dict(obj: Any) -> dict[str, Any]:
        """Convert a dataclass to a dict."""
        if hasattr(obj, "__dataclass_fields__"):
            return {k: getattr(obj, k) for k in obj.__dataclass_fields__}
        return obj


# ── Convenience ───────────────────────────────────────────────────────

def quick_snapshot() -> dict[str, Any]:
    """One-shot: capture and return a full performance snapshot."""
    return PerformanceMonitor().capture()


def quick_print():
    """One-shot: capture and print a performance snapshot."""
    PerformanceMonitor().print_snapshot()


